export function normalizeSkillName(skillName) {
  const value = String(skillName || "")
    .trim()
    .toLowerCase();

  if (
    value.includes("amazon web services") ||
    value === "aws"
  ) {
    return "aws";
  }

  if (
    value.includes("apache kafka") ||
    value === "kafka"
  ) {
    return "kafka";
  }

  if (
    value.includes("atlassian jira") ||
    value === "jira"
  ) {
    return "jira";
  }

  if (
    value.includes("javascript")
  ) {
    return "javascript";
  }

  if (
    value.includes("react")
  ) {
    return "react";
  }

  if (
    value.includes("python")
  ) {
    return "python";
  }

  if (
    value === "java" ||
    value.includes("java programming")
  ) {
    return "java";
  }

  if (
    value === "sql" ||
    value.includes("structured query")
  ) {
    return "sql";
  }

  if (
    value.includes("html")
  ) {
    return "html";
  }

  if (
    value.includes("css")
  ) {
    return "css";
  }

  if (
    value.includes("git") &&
    !value.includes("github")
  ) {
    return "git";
  }

  if (
    value.includes("github")
  ) {
    return "github";
  }

  if (
    value.includes("rest") ||
    value.includes("api")
  ) {
    return "rest_api";
  }

  if (
    value.includes("power bi")
  ) {
    return "power_bi";
  }

  if (
    value.includes("excel")
  ) {
    return "excel";
  }

  return value;
}